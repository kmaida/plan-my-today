const SOURCE_ICONS: Record<TaskSource, (props: { size?: number }) => JSX.Element> = {
  linear: LinearIcon,
  gmail: GmailIcon,
  github: GitHubIcon,
  'github-issue': GitHubIcon,
  slack: SlackIcon,
  calendar: CalendarIcon,
  docs: DocsIcon,
  'meeting-notes': MeetingNotesIcon,
}

export function SourceIcon({ source, showLabel = false, size = 16 }: SourceIconProps) {
  const label = SOURCE_LABELS[source]
  const IconComponent = SOURCE_ICONS[source]

  if (!label || !IconComponent) {
    return null
  }

  return (
    <span className="source-icon" title={label}>
      <IconComponent size={size} />
      {showLabel && <span className="source-icon__label">{label}</span>}
    </span>
  )
}

export function getSourceLabel(source: TaskSource): string {
  return SOURCE_LABELS[source] || source
}
